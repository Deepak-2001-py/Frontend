// Pure helpers that reproduce Python semantics, and rubric reply parsing.
import assert from 'node:assert/strict'
import { test } from 'node:test'

process.env.APP_ENV = 'test'
const py = await import('../src/lib/py.js')
const { parseRubricItems } = await import('../src/services/workflow/assistant.js')
const passwords = await import('../src/lib/passwords.js')

test('Python-compatible helpers', () => {
  assert.equal(py.truthy([]), false)
  assert.equal(py.truthy({}), false)
  assert.equal(py.truthy('0'), true)
  assert.equal(py.num('4'), 4)
  assert.equal(py.num(' 2.5 '), 2.5)
  assert.equal(py.num('abc', -1), -1)
  assert.equal(py.num(null, -1), -1)
  assert.equal(py.num(true), 1)
  assert.equal(py.pyRound(2.5), 2)
  assert.equal(py.pyRound(3.5), 4)
  assert.equal(py.pyRound(-0.4), -0)
  assert.equal(py.pyStr(null), 'None')
  assert.equal(py.trunc('héllo wörld', 5), 'héllo')
  assert.deepEqual(py.sortBy([{ k: [2, 'b'] }, { k: [1, 'z'] }, { k: [2, 'a'] }], (x) => x.k).map((x) => x.k), [[1, 'z'], [2, 'a'], [2, 'b']])
  assert.equal(py.isoDate('2030-02-30'), null)
  assert.equal(py.isoDate('2030-01-10T09:00:00+00:00'), '2030-01-10')
  assert.match(py.isoUtc(new Date(Date.UTC(2026, 0, 2, 3, 4, 5))), /^2026-01-02T03:04:05\+00:00$/)
  assert.equal(py.pyRepr(null), 'None')
  assert.equal(py.pyRepr("it's"), "'it\\'s'")
})

test('rubric replies are parsed leniently', () => {
  assert.deepEqual(parseRubricItems('{"items":[{"question_number":"1"}]}'), [{ question_number: '1' }])
  assert.deepEqual(parseRubricItems('Here you go:\n```json\n{"items":[{"question_number":"2"}]}\n```'), [{ question_number: '2' }])
  assert.equal(parseRubricItems('no json here'), null)
  assert.equal(parseRubricItems('{"items": oops}'), null)
  assert.equal(parseRubricItems(null), null)
})

test('password hashes are compatible with the Python Lambdas', async () => {
  // Generated by authetication.py: base64(32-byte salt + PBKDF2-SHA256(100k)) of "Password123!"
  const salt = Buffer.alloc(32, 7)
  const { pbkdf2Sync } = await import('node:crypto')
  const pythonStyle = Buffer.concat([salt, pbkdf2Sync('Password123!', salt, 100000, 32, 'sha256')]).toString('base64')
  assert.equal(await passwords.verifyLoginPassword(pythonStyle, 'Password123!'), true)
  assert.equal(await passwords.verifyLoginPassword(pythonStyle, 'password123!'), false)
  const admin = await passwords.hashAdminPassword('AdminPass123')
  assert.match(admin, /^[0-9a-f]{32}:[0-9a-f]{64}$/)
  assert.equal(await passwords.verifyAdminPassword('AdminPass123', admin), true)
  assert.equal(passwords.passwordProblem('short1A'), 'Password must be at least 8 characters.')
  assert.equal(passwords.passwordProblem('longenough1'), 'Password must include an uppercase letter.')
  assert.equal(passwords.passwordProblem('Longenough'), 'Password must include a number.')
  assert.equal(passwords.passwordProblem('Longenough1'), null)
})
